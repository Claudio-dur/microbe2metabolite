"""Re-check every section-3 data fact on the downloaded raw data (run by `make data`).

Prints the report, writes results/data_checks.md and exits with status 1 if any fact fails.
The external test cohort is opened here only through the guarded loaders, which log the access.

    python scripts/check_data.py [--raw-dir data/raw] [--facts configs/data_facts.yaml]
"""

from __future__ import annotations

import argparse
import sys
import time
from collections.abc import Sequence
from pathlib import Path

from m2m import data, paths
from m2m.tracking import utc_now

REPORT_NAME = "data_checks.md"


def main(argv: Sequence[str] | None = None) -> int:
    args = _parse_args(argv)
    start = time.perf_counter()
    results = data.evaluate_section3_facts(args.raw_dir, args.facts)
    seconds = time.perf_counter() - start

    table = data.format_fact_report(results)
    summary = _summary(results, seconds)
    report_path = paths.RESULTS / REPORT_NAME
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(_markdown(table, summary, args))

    print("\n".join(table))
    print(f"\n{summary}\nReport written to {_display(report_path)}")
    failed = [result for result in results if not result.passed]
    for result in failed:
        print(f"FAIL {result.key}: observed {result.observed}", file=sys.stderr)
    return 1 if failed else 0


def _parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--raw-dir", type=Path, default=None, help="raw-data root (default: paths.DATA_RAW)"
    )
    parser.add_argument(
        "--facts", type=Path, default=None, help="facts file (default: configs/data_facts.yaml)"
    )
    return parser.parse_args(argv)


def _summary(results: Sequence[data.FactResult], seconds: float) -> str:
    n_failed = sum(not result.passed for result in results)
    n_differ = sum(result.passed and result.brief is not None for result in results)
    return (
        f"{len(results)} facts: {len(results) - n_failed} passed, {n_failed} failed "
        f"({n_differ} passed with a documented difference from the brief); {seconds:.1f} s."
    )


def _markdown(table: Sequence[str], summary: str, args: argparse.Namespace) -> str:
    raw_dir = args.raw_dir if args.raw_dir is not None else paths.DATA_RAW
    facts = args.facts if args.facts is not None else paths.CONFIGS / data.FACTS_FILE
    header = [
        "# Section-3 data checks",
        "",
        f"Generated by `scripts/check_data.py` on {utc_now()}.",
        f"Raw data: `{_display(raw_dir)}`. Expected values: `{_display(facts)}`.",
        "",
        summary,
        "",
    ]
    return "\n".join([*header, *table, ""])


def _display(path: Path) -> str:
    """Repo-relative when possible, so the committed report holds no machine-specific paths."""
    try:
        return str(Path(path).resolve().relative_to(paths.REPO_ROOT.resolve()))
    except ValueError:
        return str(path)


if __name__ == "__main__":
    sys.exit(main())
